#!/usr/bin/env python3
"""Make the boot-eyes nose bridge for orb 3: a mosaic of tiles cut from the
circuit boards of the Hands-On Tech hand (images/booteyes/hand-source.jpg, the
1408x768 render the built-in logo comes from).

Run from the repo root (needs Pillow; the seed is fixed, so the output repeats):

    uv run --with pillow python tools/make_nose.py

Writes:
  images/booteyes/nose.jpg                  240x240 baseline JPEG, to look at
  firmware/src/core/booteyes/noseJpg.h      the same bytes as a C array; only
                                            BOOT_EYES builds include it
"""
import io
import math
import random
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw, ImageFilter

SOURCE = Path("images/booteyes/hand-source.jpg")
OUT_JPG = Path("images/booteyes/nose.jpg")
OUT_H = Path("firmware/src/core/booteyes/noseJpg.h")
N = 240
# Board areas of the hand (source-image pixels): the palm's glowing traces,
# the Arduino, the index, ring and little finger boards
REGIONS = [(620, 540, 800, 680), (675, 70, 735, 225), (592, 150, 650, 262),
           (755, 160, 815, 272), (845, 190, 900, 330), (700, 545, 790, 600)]


def mosaic(src: Image.Image) -> Image.Image:
    """Split the orb into board-sized rectangles, each a random cut of a board,
    with a 1 px dark gap all round like the hand's seams."""
    tiles = Image.new("RGB", (N, N))

    def fill(x0, y0, x1, y1, depth):
        w, h = x1 - x0, y1 - y0
        if depth > 0 and (w > 64 or h > 64 or (random.random() < 0.5 and min(w, h) > 30)):
            if w >= h:
                c = x0 + int(w * random.uniform(0.35, 0.65))
                fill(x0, y0, c, y1, depth - 1)
                fill(c, y0, x1, y1, depth - 1)
            else:
                c = y0 + int(h * random.uniform(0.35, 0.65))
                fill(x0, y0, x1, c, depth - 1)
                fill(x0, c, x1, y1, depth - 1)
            return
        rx0, ry0, rx1, ry1 = random.choice(REGIONS)
        s = random.uniform(0.7, 1.1)
        cw = min(max(4, int(w / s)), rx1 - rx0)
        ch = min(max(4, int(h / s)), ry1 - ry0)
        sx, sy = random.randint(rx0, rx1 - cw), random.randint(ry0, ry1 - ch)
        t = src.crop((sx, sy, sx + cw, sy + ch)).resize((w - 2, h - 2), Image.LANCZOS)
        if random.random() < 0.5:
            t = t.transpose(Image.ROTATE_180)
        tiles.paste(t, (x0 + 1, y0 + 1))

    fill(0, 0, N, N, 8)
    return tiles


def half_width(y: int) -> float:
    """Saddle just above eye level (the eyes sit at mid-height on orbs 2 and
    4), widening down toward the tip."""
    if y < 90:
        return 44 + 4 * ((90 - y) / 90) ** 2
    return 44 + 44 * ((y - 90) / 150) ** 1.6


def main():
    random.seed(7)
    tiles = mosaic(Image.open(SOURCE).convert("RGB"))
    mask, shade, fade = (Image.new("L", (N, N)) for _ in range(3))
    mp, sp, fp = mask.load(), shade.load(), fade.load()
    for y in range(N):
        w = half_width(y)
        top = min(1, y / 40)  # fades into the forehead
        for x in range(N):
            fp[x, y] = int(255 * min(1, y / 50))
            d = abs(x - N / 2 + 0.5) / w
            if d <= 1:
                mp[x, y] = int(255 * min(1, (1 - d) * 6))
                # lit along the ridge, falling away to the sides
                sp[x, y] = int(255 * top * min(1, 0.45 + 0.75 * math.cos(d * math.pi / 2) ** 1.2))
    body = ImageChops.multiply(tiles, Image.merge("RGB", [shade] * 3))
    # blue-white rim light, like the hand's outline
    edge = mask.filter(ImageFilter.FIND_EDGES).filter(ImageFilter.GaussianBlur(1.2))
    rim = Image.merge("RGB", [edge.point(lambda v: int(v * 0.55)), edge.point(lambda v: int(v * 0.8)), edge])
    rim = ImageChops.multiply(rim, Image.merge("RGB", [fade] * 3))
    out = ImageChops.add(Image.composite(body, Image.new("RGB", (N, N)), mask), rim)

    buf = io.BytesIO()
    out.save(buf, "JPEG", quality=80, progressive=False, optimize=True)  # TJpg_Decoder: baseline only
    data = buf.getvalue()
    OUT_JPG.write_bytes(data)
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    OUT_H.write_text(
        "#pragma once\n"
        "// Generated by tools/make_nose.py from images/booteyes/hand-source.jpg - do not edit.\n"
        "// The boot-eyes nose bridge for orb 3, a 240x240 baseline JPEG.\n"
        "#include <pgmspace.h>\n#include <stdint.h>\n\n"
        f"static const uint8_t kNoseJpg[{len(data)}] PROGMEM = {{\n    " + ",\n    ".join(rows) + "\n};\n")
    print(f"{OUT_JPG} {len(data)} bytes; {OUT_H}")


if __name__ == "__main__":
    main()
